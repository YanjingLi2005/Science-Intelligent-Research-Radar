export function translateInterface(text: string): string {
  const trimmed = text.trim();
  if (!trimmed) return text;
  const translated = copy[trimmed];
  if (translated) return text.replace(trimmed, translated);
  for (const [pattern, replacement] of dynamicCopy) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  for (const [prefix, translatedPrefix] of Object.entries(prefixes)) {
    if (trimmed.startsWith(prefix)) return text.replace(prefix, translatedPrefix);
  }
  return text;
}
